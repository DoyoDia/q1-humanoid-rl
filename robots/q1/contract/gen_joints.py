#!/usr/bin/env python3
"""Generate joints.yaml from the vendor URDF + MJCF + the on-robot robot_model.yaml.

The joint ORDER is not derived — it is the contract, copied verbatim from the robot's
cfg/robot/q1_t2d0/rl/mimic_opensource_v2_config.yaml `seq`. Everything else is derived
so the numbers cannot drift from the models.

    python3 gen_joints.py --urdf ../../../_ref/q1_v3/urdf/q1_v3.urdf \
                          --mjcf ../../../_ref/q1_v3/xml/q1_v3_mc.xml \
                          --out  joints.yaml
"""

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

# --- THE CONTRACT: 22 joints, this exact order. Do not sort, do not regenerate. ---
# Source: robot:/robot/software/mc/bin/cfg/robot/q1_t2d0/rl/
#         mimic_opensource_v2_config.yaml -> BaseConfig.seq (== action_seq)
ORDER = [
    "left_hip_pitch_joint", "left_hip_roll_joint", "left_hip_yaw_joint",
    "left_knee_joint", "left_ankle_pitch_joint", "left_ankle_roll_joint",
    "right_hip_pitch_joint", "right_hip_roll_joint", "right_hip_yaw_joint",
    "right_knee_joint", "right_ankle_pitch_joint", "right_ankle_roll_joint",
    "waist_roll_joint", "waist_yaw_joint",
    "left_shoulder_pitch_joint", "left_shoulder_roll_joint",
    "left_shoulder_yaw_joint", "left_elbow_joint",
    "right_shoulder_pitch_joint", "right_shoulder_roll_joint",
    "right_shoulder_yaw_joint", "right_elbow_joint",
]

# From the robot's cfg/robot/q1_t2d0/robot_model.yaml. Read back 2026-09-19.
# Its lower/upper_position are STALE (copied from the QD1 quadruped line) and are NOT
# enforced as position clamps -- proof: the vendor's own walk_run.yaml default_dof_pos
# puts knee at 0.6982 and ankle_pitch at -0.3582, both outside those "limits", and the
# robot walks. Only the velocity/effort caps below are taken from this file.
ROBOT_MODEL_CAPS = {j: (33.0, 20.94) for j in ORDER}  # (max_effort N*m, max_velocity rad/s)
ROBOT_MODEL_CAPS["left_shoulder_roll_joint"] = (14.0, 27.23)
ROBOT_MODEL_CAPS["right_shoulder_roll_joint"] = (14.0, 27.23)


def urdf_limits(path):
    out = {}
    for j in ET.parse(path).getroot().findall("joint"):
        lim = j.find("limit")
        if lim is None:
            continue
        out[j.get("name")] = dict(
            lower=float(lim.get("lower")), upper=float(lim.get("upper")),
            effort=float(lim.get("effort")), velocity=float(lim.get("velocity")),
        )
    return out


def mjcf_limits(path):
    import mujoco
    m = mujoco.MjModel.from_xml_path(str(path))
    out = {}
    for i in range(m.njnt):
        name = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, i)
        if m.jnt_type[i] <= 1:      # free / ball -> no scalar range
            continue
        lo, hi = m.jnt_range[i]
        dof = m.jnt_dofadr[i]
        out[name] = dict(lower=float(lo), upper=float(hi),
                         armature=float(m.dof_armature[dof]))
    return out


def main():
    p = argparse.ArgumentParser()
    here = Path(__file__).resolve().parent
    p.add_argument("--urdf", default=here / "../../../_ref/q1_v3/urdf/q1_v3.urdf")
    p.add_argument("--mjcf", default=here / "../../../_ref/q1_v3/xml/q1_v3_mc.xml")
    p.add_argument("--out", default=here / "joints.yaml")
    a = p.parse_args()

    u, x = urdf_limits(a.urdf), mjcf_limits(a.mjcf)

    missing = [j for j in ORDER if j not in u or j not in x]
    if missing:
        raise SystemExit(f"joints in the contract but missing from a model: {missing}")
    extra_urdf = sorted(set(u) - set(ORDER))
    extra_mjcf = sorted(set(x) - set(ORDER))

    lines = [
        "# GENERATED by gen_joints.py -- do not edit by hand.",
        "# order: the deployment contract (mimic_opensource_v2_config.yaml `seq`), never sorted.",
        "# position limits: from the URDF, which agrees bit-for-bit with q1_v3_mc.xml.",
        "# effort/velocity: per-joint min(URDF, robot_model.yaml) -- the conservative choice.",
        "",
        f"n_joints: {len(ORDER)}",
        "source:",
        f"  urdf: {Path(a.urdf).name}",
        f"  mjcf: {Path(a.mjcf).name}",
        "  order: robot:/robot/software/mc/bin/cfg/robot/q1_t2d0/rl/mimic_opensource_v2_config.yaml#seq",
        "  caps:  robot:/robot/software/mc/bin/cfg/robot/q1_t2d0/robot_model.yaml",
        "",
        "joints:",
    ]
    for i, j in enumerate(ORDER):
        eff = min(u[j]["effort"], ROBOT_MODEL_CAPS[j][0])
        vel = min(u[j]["velocity"], ROBOT_MODEL_CAPS[j][1])
        assert abs(u[j]["lower"] - x[j]["lower"]) < 1e-9 and abs(u[j]["upper"] - x[j]["upper"]) < 1e-9, \
            f"URDF and MJCF disagree on {j}"
        lines += [
            f"  - index: {i}",
            f"    name: {j}",
            f"    lower: {u[j]['lower']:.6g}",
            f"    upper: {u[j]['upper']:.6g}",
            f"    effort: {eff:g}          # URDF {u[j]['effort']:g} / robot_model {ROBOT_MODEL_CAPS[j][0]:g}",
            f"    velocity: {vel:g}        # URDF {u[j]['velocity']:g} / robot_model {ROBOT_MODEL_CAPS[j][1]:g}",
            f"    armature: {x[j]['armature']:g}",
        ]
    lines += [
        "",
        "# Joints present in the URDF but NOT in the MJCF and NOT in the deployment contract.",
        "# The 22-joint contract is authoritative; do not add these to the action space.",
        "urdf_only: " + ("[" + ", ".join(extra_urdf) + "]" if extra_urdf else "[]"),
        "mjcf_only: " + ("[" + ", ".join(extra_mjcf) + "]" if extra_mjcf else "[]"),
        "",
        "# Firmware constraints on /aima/hal/joint/command (SDK 接口说明.md, unchanged through v4 of 2026-10-10).",
        "command:",
        "  max_step_rad: 0.2          # per frame; larger jumps risk gearbox / bus overcurrent",
        "  publish_hz: [500, 1000]    # below 100 Hz trips the watchdog",
        "  stamp: monotonic onboard clock; out-of-order frames are dropped silently",
        "  shutdown_frame: {stiffness: 0.0, damping: 5.0}   # mandatory before disconnecting",
        "",
    ]
    Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {a.out}  ({len(ORDER)} joints)")
    if extra_urdf:
        print(f"note: URDF has {len(extra_urdf)} joint(s) outside the contract: {extra_urdf}")


if __name__ == "__main__":
    main()
